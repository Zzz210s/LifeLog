-- 023: 属性名存到边上(设计 2026-10-06 §2 修订)。
-- 箭头 `A --(属性名)--> B` 读作「A 具有属性名所表示的属性,值是 B」,例
-- `作者/丸尾常喜 --(国籍)--> 地点轴/日本`。属性名是**边**的属性,不是被指向标签的属性 ——
-- 同一个 `地点轴/日本` 可以既是「国籍」又是「出生地」,所以不能借用目标标签自己名字里的
-- md 备注(`[国籍](国别)`,那只驱动标签名的悬浮显示,与本列无关)。
--
-- 列由 Rust 钩子 `ensure_link_remark_column` 按列存在性 ADD COLUMN(SQLite 的
-- ALTER TABLE 没有 IF NOT EXISTS,重放会报 duplicate column name,写不进纯 SQL);
-- 本文件只承载口径说明,可重放。
--
-- 不校验历史数据:存量边(本机真实库 24 条)的 remark 取列默认值,显示时沿用 R12 回退
-- (空属性名只显示目标名)。所有写入都显式带 target_type='tag',笔记链接行(target_type='note')
-- 与本列无关,新列对它们恒为空串。
